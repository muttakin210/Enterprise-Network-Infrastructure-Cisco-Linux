#!/usr/bin/env bash
# install-netbox.sh  -  NetBox (IPAM / DCIM source of truth) on srv01, following the official guide
# https://netboxlabs.com/docs/netbox/installation/
# Usage (on the VM, from the repo root):  sudo ./ipam/netbox/install-netbox.sh
# Idempotent. NetBox 4.7 needs Python >= 3.12 and PostgreSQL >= 15, newer than Ubuntu 22.04 ships,
# so Python comes from the deadsnakes PPA and PostgreSQL from the official PGDG repository.
# Web UI on port 8082 (Nginx -> gunicorn 127.0.0.1:8001).
set -euo pipefail
[[ $EUID -eq 0 ]] || { echo "run with sudo"; exit 1; }
HERE="$(cd "$(dirname "$0")" && pwd)"
NB_VER=${NB_VER:-4.7.4}
PY=python3.12
PG=17
SECRETS=/root/lab-secrets.env
log() { printf '\n=== %s ===\n' "$*"; }
gen() { tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-20}"; }

log "Secrets"
grep -q '^NETBOX_DB_PASS=' $SECRETS     || echo "NETBOX_DB_PASS=$(gen)" >>$SECRETS
grep -q '^NETBOX_ADMIN_PASS=' $SECRETS  || echo "NETBOX_ADMIN_PASS=$(gen)" >>$SECRETS
grep -q '^NETBOX_SECRET_KEY=' $SECRETS  || echo "NETBOX_SECRET_KEY=$(gen 60)" >>$SECRETS
grep -q '^NETBOX_TOKEN_PEPPER=' $SECRETS || echo "NETBOX_TOKEN_PEPPER=$(gen 60)" >>$SECRETS
# shellcheck disable=SC1090
source $SECRETS

log "Packages: Python 3.12 (deadsnakes), PostgreSQL $PG (PGDG), Redis"
export DEBIAN_FRONTEND=noninteractive
if ! ls /etc/apt/sources.list.d/ | grep -q deadsnakes; then
  add-apt-repository -y ppa:deadsnakes/ppa
fi
if [[ ! -f /etc/apt/sources.list.d/pgdg.list ]]; then
  install -d /usr/share/postgresql-common/pgdg
  curl -fsSL -o /usr/share/postgresql-common/pgdg/apt.postgresql.org.asc https://www.postgresql.org/media/keys/ACCC4CF8.asc
  echo "deb [signed-by=/usr/share/postgresql-common/pgdg/apt.postgresql.org.asc] https://apt.postgresql.org/pub/repos/apt jammy-pgdg main" \
    >/etc/apt/sources.list.d/pgdg.list
fi
apt-get update -q
apt-get install -y -q $PY $PY-venv $PY-dev postgresql-$PG redis-server build-essential \
  libxml2-dev libxslt1-dev libffi-dev libpq-dev libssl-dev zlib1g-dev

log "PostgreSQL"
systemctl enable --now postgresql
sudo -u postgres psql -v ON_ERROR_STOP=1 -q <<EOF
SELECT 'CREATE DATABASE netbox' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname='netbox')\gexec
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='netbox') THEN CREATE ROLE netbox LOGIN; END IF;
END \$\$;
ALTER ROLE netbox WITH PASSWORD '$NETBOX_DB_PASS';
ALTER DATABASE netbox OWNER TO netbox;
EOF
sudo -u postgres psql -q -d netbox -c 'GRANT CREATE ON SCHEMA public TO netbox;'
# small lab: keep PostgreSQL memory low
PGCONF=/etc/postgresql/$PG/main/conf.d/90-lab.conf
printf "shared_buffers = 64MB\nmax_connections = 40\n" >$PGCONF
systemctl restart postgresql
systemctl enable --now redis-server

log "NetBox $NB_VER code"
id netbox &>/dev/null || useradd --system --home-dir /opt/netbox --no-create-home netbox
if [[ ! -d /opt/netbox-$NB_VER ]]; then
  curl -fsSL -o /tmp/netbox.tgz https://github.com/netbox-community/netbox/archive/refs/tags/v$NB_VER.tar.gz
  tar xzf /tmp/netbox.tgz -C /opt
fi
ln -sfn /opt/netbox-$NB_VER /opt/netbox
chown -R netbox:netbox /opt/netbox-$NB_VER/netbox/media /opt/netbox-$NB_VER/netbox/reports /opt/netbox-$NB_VER/netbox/scripts 2>/dev/null || true

log "configuration.py"
C=/opt/netbox/netbox/netbox/configuration.py
cat >$C <<EOF
# Generated by ipam/netbox/install-netbox.sh. Secrets come from /root/lab-secrets.env.
ALLOWED_HOSTS = ['*']
DATABASES = {
    'default': {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': 'netbox', 'USER': 'netbox', 'PASSWORD': '$NETBOX_DB_PASS',
        'HOST': 'localhost', 'PORT': '', 'CONN_MAX_AGE': 300,
    }
}
REDIS = {
    'tasks':   {'HOST': 'localhost', 'PORT': 6379, 'DATABASE': 0, 'SSL': False},
    'caching': {'HOST': 'localhost', 'PORT': 6379, 'DATABASE': 1, 'SSL': False},
}
SECRET_KEY = '$NETBOX_SECRET_KEY'
API_TOKEN_PEPPERS = {1: '$NETBOX_TOKEN_PEPPER'}
TIME_ZONE = 'Asia/Dhaka'
EOF
chown root:netbox $C; chmod 640 $C

log "Virtualenv, requirements, migrations, static files (upgrade.sh)"
cd /opt/netbox
PYTHON=/usr/bin/$PY ./upgrade.sh >/tmp/netbox-upgrade.log 2>&1 || { tail -30 /tmp/netbox-upgrade.log; exit 1; }
tail -3 /tmp/netbox-upgrade.log

log "Superuser"
if ! sudo -u netbox /opt/netbox/venv/bin/python netbox/manage.py shell -c \
     "from django.contrib.auth import get_user_model as g; import sys; sys.exit(0 if g().objects.filter(username='admin').exists() else 1)" 2>/dev/null; then
  DJANGO_SUPERUSER_PASSWORD="$NETBOX_ADMIN_PASS" /opt/netbox/venv/bin/python netbox/manage.py \
    createsuperuser --noinput --username admin --email netadmin@corp.lab
fi

log "gunicorn + systemd (2 workers for a 3 GB VM)"
cp -f contrib/gunicorn.py /opt/netbox/gunicorn.py
sed -i "s/^bind = .*/bind = '127.0.0.1:8001'/; s/^workers = .*/workers = 2/; s/^threads = .*/threads = 2/" /opt/netbox/gunicorn.py
cp -f contrib/*.service /etc/systemd/system/
chown -R netbox:netbox /opt/netbox/netbox/media
systemctl daemon-reload
systemctl enable --now netbox netbox-rq
systemctl restart netbox netbox-rq

log "Nginx site on :8082"
install -m 644 "$HERE/nginx-netbox.conf" /etc/nginx/sites-available/netbox
ln -sf /etc/nginx/sites-available/netbox /etc/nginx/sites-enabled/netbox
nginx -t && systemctl reload nginx

log "Firewall"
ufw allow from 192.168.10.0/24 to any port 8082 proto tcp comment 'NetBox from Admin VLAN'
ufw allow from 10.99.0.0/24    to any port 8082 proto tcp comment 'NetBox from WireGuard admins'
ufw allow from 10.0.2.2        to any port 8082 proto tcp comment 'NetBox via VirtualBox NAT (host only)'

log "Wait for NetBox"
for _ in $(seq 60); do curl -fs -o /dev/null http://127.0.0.1:8082/login/ && break; sleep 2; done
curl -s -o /dev/null -w 'login page HTTP %{http_code}\n' http://127.0.0.1:8082/login/

log "Import the lab (sites, VLANs, prefixes, devices, interfaces, IPs, cables)"
NETBOX_ADMIN_PASS="$NETBOX_ADMIN_PASS" python3 "$HERE/import-lab.py" "$HERE/../../topology/addressing-plan.csv"
